//! The parameter registry's dump (package R1, `design/ecology-parameter-registry-2026-09-28.md`):
//! every path with its value, unit and range, after the layers a run would apply.
//!
//! ```text
//! cargo run -p cubarium-voxel-sim --example params                       # every leaf
//! cargo run -p cubarium-voxel-sim --example params -- --config config/desktop/terrarium.toml \
//!     --set fauna.founders.frondgrazer.core.maintenance_per_s=0.002
//! cargo run -p cubarium-voxel-sim --example params -- --config config/desktop/terrarium.toml \
//!     --params config/training/curiosity-2026-10-02/C2-mean.toml   # a genome over the preset
//! cargo run -p cubarium-voxel-sim --example params -- --markdown         # design/backlog.md §1
//! cargo run -p cubarium-voxel-sim --example params -- --toml             # what a run writes
//! cargo run -p cubarium-voxel-sim --example params -- --write design/parameters.md
//! ```
//!
//! `--params FILE` is a search genome (`[[gene]]`), expanded and decoded over the
//! `--config` file's tables as the binary's `--params` decodes it, before any `--set`. A
//! search file's `[base]` is not read: `--config` is the base.
//!
//! `--write FILE` writes the markdown dump of the defaults as the whole of `FILE`, a
//! generated file (`design/parameters.md`).

use cubarium_voxel::genome::SearchFile;
use cubarium_voxel_sim::params::{Layers, Params};

const HEADER: &str = "# Ecology parameters: the registry dump\n\n\
<!-- Generated by `cargo run -p cubarium-voxel-sim --example params -- --write design/parameters.md`. Do not edit by hand. -->\n\n\
Every number of the voxel world's `Config`, the plants' `FloraConfig` and the animals' \
`FaunaConfig`, one row per path, at the code defaults \
(`design/ecology-parameter-registry-2026-09-28.md`, package R1). Set them in a config \
TOML's `[world]` / `[flora]` / `[fauna]` tables or with `--set PATH=VALUE`; a run writes \
its resolved set as `params.toml` beside its output.\n";

fn main() {
    let mut args = std::env::args().skip(1);
    let mut layers = Layers::default();
    let mut mode = "list";
    let mut target: Option<String> = None;
    let mut genome_text: Option<(String, String)> = None;
    while let Some(a) = args.next() {
        match a.as_str() {
            "--config" => {
                let path = args.next().expect("--config FILE");
                let text = std::fs::read_to_string(&path)
                    .unwrap_or_else(|e| panic!("cannot read {path}: {e}"));
                layers.file = Some(text.parse().unwrap_or_else(|e| panic!("{path}: {e}")));
            }
            "--params" => {
                let path = args.next().expect("--params FILE");
                let text = std::fs::read_to_string(&path)
                    .unwrap_or_else(|e| panic!("cannot read {path}: {e}"));
                genome_text = Some((path, text));
            }
            "--set" => layers.sets.push(args.next().expect("--set path=value")),
            "--markdown" => mode = "markdown",
            "--toml" => mode = "toml",
            "--write" => {
                mode = "write";
                target = Some(args.next().expect("--write FILE"));
            }
            other => panic!("unknown argument {other}"),
        }
    }
    // The genome expands over the config's own tables (a search file's genes may name a
    // lineage only the config founds, e.g. roster.toml's nine on the terrarium), as the
    // binary's `--params` decodes it over them. A search file's `[base]` is not read here:
    // `--config` is the base.
    let genome = genome_text.map(|(path, text)| {
        let base = Params::resolve(&Layers { file: layers.file.clone(), ..Layers::default() })
            .unwrap_or_else(|e| {
                eprintln!("params: --config: {e}");
                std::process::exit(2)
            });
        SearchFile::parse(&text)
            .and_then(|f| base.expand_genome(f))
            .unwrap_or_else(|e| {
                eprintln!("params: --params {path}: {e}");
                std::process::exit(2)
            })
    });
    let apply = |p: &mut Params| {
        if let Some(g) = &genome {
            p.apply_genome(g).unwrap_or_else(|e| {
                eprintln!("params: --params: {e}");
                std::process::exit(2)
            });
        }
    };
    if genome.is_some() {
        layers.genome = Some(&apply);
    }
    let params = Params::resolve(&layers).unwrap_or_else(|e| {
        eprintln!("params: {e}");
        std::process::exit(2)
    });
    match mode {
        "markdown" => print!("{}", params.markdown().expect("the markdown")),
        "toml" => print!("{}", params.to_toml().expect("the TOML")),
        "write" => {
            let path = target.expect("a file");
            let block = params.markdown().expect("the markdown");
            std::fs::write(&path, format!("{HEADER}{block}"))
                .unwrap_or_else(|e| panic!("{path}: {e}"));
            eprintln!("wrote the registry dump to {path}");
        }
        _ => {
            for line in params.dump().expect("the dump") {
                println!(
                    "{} = {}\t# {} {}",
                    line.path, line.value, line.row.unit, line.row.range
                );
            }
        }
    }
}
